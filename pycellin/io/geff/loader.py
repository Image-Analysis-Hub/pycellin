def _recursive_dict_search(
    data: dict[str, Any], target_key: str
) -> dict[str, Any] | None:
    """
    Recursively search for a target key in a nested dictionary structure.

    Parameters
    ----------
    data : dict
        The dictionary to search through.
    target_key : str
        The key to search for.

    Returns
    -------
    dict[str, Any] | None
        The dict associated with the target key if found, None otherwise.
    """
    if not isinstance(data, dict):
        return None
    if target_key in data:  # search in the current level
        return data[target_key]
    for value in data.values():  # recursive search in nested dictionaries
        if isinstance(value, dict):
            result = _recursive_dict_search(value, target_key)
            if result is not None:
                return result
    return None


def _lin_ids_match_components(graph: nx.Graph, lin_id_key: str) -> bool:
    """
    Check whether a node property can identify the lineages of a graph.

    Each lineage is a connected component of the graph. The property can identify
    them if the nodes of a component don't have different values, and if two
    components don't share a value. Nodes without the property, or with a None
    value, are ignored: they get the value of their component when the graph is
    split into lineages.

    Parameters
    ----------
    graph : nx.Graph
        The graph to check.
    lin_id_key : str
        Name of the node property to check.

    Returns
    -------
    bool
        True if the property can identify the lineages, False otherwise.
    """
    if graph.is_directed():
        components = nx.weakly_connected_components(graph)
    else:
        components = nx.connected_components(graph)
    used_lin_ids = set()
    for component in components:
        lin_ids = {graph.nodes[node].get(lin_id_key) for node in component} - {None}
        if len(lin_ids) > 1:
            return False
        if lin_ids:
            lin_id = next(iter(lin_ids))
            if lin_id in used_lin_ids:
                return False
            used_lin_ids.add(lin_id)
    return True


def _identify_lin_id_prop(
    lin_id_key: str | None,
    geff_track_node_props: dict[Literal["lineage", "tracklet"], str] | None,
    geff_graph: nx.DiGraph,
) -> str | None:
    """
    Identify the lineage ID key from user input or GEFF metadata.

    If ``lin_id_key`` is provided, the function will check that the property exists
    in all nodes of the graph. If not provided, the function will try to infer it
    from the 'lineage' entry of the GEFF track_node_props, then from a 'lineage_id'
    property of the graph, if its values can identify the lineages. If that fails,
    lineage IDs will be autogenerated.

    Parameters
    ----------
    lin_id_key : str | None
        Name of the property to identify lineages.
    geff_track_node_props : dict[Literal["lineage", "tracklet"], str] | None
        The track_node_props from GEFF metadata.
    geff_graph : nx.DiGraph
        The GEFF graph.

    Returns
    -------
    str | None
        The identified lineage ID key, or None if not found or inferred.

    Warns
    -----
    UserWarning
        If the provided ``lin_id_key`` is not found in the GEFF graph.
    """
    # TODO: but what if the property is present but not on all nodes?
    error_stack_level = 3

    valid_lin_id_key: str | None = None
    if lin_id_key is not None:
        if _graph_has_node_prop(geff_graph, lin_id_key):
            valid_lin_id_key = lin_id_key
        else:
            logger.info(
                f"The provided property '{lin_id_key}' is not present in the graph. "
                "Lineage identifier will be infered from GEFF metadata.",
                stacklevel=error_stack_level,
            )
            lin_id_key = None

    if lin_id_key is None:
        if (
            geff_track_node_props is not None
            and geff_track_node_props.get("lineage") is not None
        ):
            valid_lin_id_key = geff_track_node_props["lineage"]
            logger.info(
                f"Lineage identifier inferred from GEFF track_node_props: "
                f"'{valid_lin_id_key}'.",
                stacklevel=error_stack_level,
            )
        elif _graph_has_node_prop(geff_graph, "lineage_id"):
            if _lin_ids_match_components(geff_graph, "lineage_id"):
                valid_lin_id_key = "lineage_id"
                logger.info(
                    "Lineage identifier inferred from existing graph property: "
                    "'lineage_id'.",
                    stacklevel=error_stack_level,
                )
            else:
                logger.warning(
                    "The graph property 'lineage_id' cannot be used as lineage "
                    "identifier: its values don't match the disconnected parts of the "
                    "graph. Lineage IDs will be autogenerated.",
                    stacklevel=error_stack_level,
                )
                valid_lin_id_key = None
        else:
            logger.warning(
                "No lineage identifier found in GEFF metadata. "
                "Lineage IDs will be autogenerated.",
                stacklevel=error_stack_level,
            )
            valid_lin_id_key = None

    return valid_lin_id_key


def _identify_time_prop(
    time_key: str | None,
    geff_md: geff.GeffMetadata | None,
    geff_graph: nx.DiGraph,
) -> str:
    """
    Identify the time property from argument or GEFF metadata.

    If a time key is provided, the function will check that it exists in the graph.
    If not provided or if it doesn't exist, the function will try to infer it
    from the GEFF metadata, first from the display hints, then from the axes.
    In case the function fallbacks to the GEFF axes, it will take time axes in order
    and check if the corresponding key exists in the graph. The first one to be found
    will be returned as the time property.

    Parameters
    ----------
    time_key : str | None
        The key provided to identify time points.
    geff_md : geff.GeffMetadata | None
        The GEFF metadata.
    geff_graph : nx.DiGraph
        The GEFF graph.

    Returns
    -------
    str
        The identified time property.

    Raises
    ------
    ValueError
        If no time property is found or inferred.

    Warns
    -----
    UserWarning
        If the provided time_key is not on every node of the graph, triggering
        fallback inference from GEFF metadata.
    UserWarning
        If a valid time property is inferred from display hints.
    UserWarning
        If a valid time property is inferred from axes.
    """
    if time_key is not None and not _graph_has_node_prop(geff_graph, time_key):
        logger.warning(
            f"The property '{time_key}' given as time_prop is not on every node of the "
            "GEFF graph, so the time property will be inferred from the GEFF metadata "
            "instead, if possible.",
            stacklevel=3,
        )
        time_key = None

    # Fallback to GEFF display hints.
    hints = geff_md.display_hints if geff_md is not None else None
    if time_key is None and hints is not None:
        time_key = getattr(hints, "display_time", None)
        if time_key is not None:
            if _graph_has_node_prop(geff_graph, time_key):
                logger.info(
                    f"Valid time property inferred from display hints: '{time_key}'.",
                    stacklevel=3,
                )
            else:
                time_key = None

    # Fallback to GEFF axes.
    axes = geff_md.axes if geff_md is not None else None
    if time_key is None and axes is not None:
        time_axes = [axis for axis in axes if axis.type == "time"]
        for axis in time_axes:
            if axis.name is not None and _graph_has_node_prop(geff_graph, axis.name):
                time_key = axis.name
                logger.info(
                    f"Valid time property inferred from axes: '{time_key}'.",
                    stacklevel=3,
                )
                break

    if time_key is None:
        raise ValueError(
            "No valid time property found. Please provide a valid property argument "
            "or ensure that the GEFF file contains a time axis or a time display hint."
        )

    return time_key


_COORDINATES = ("x", "y", "z")


def _coordinate_from_name(name: str) -> str | None:
    """
    Return the coordinate ('x', 'y' or 'z') that a property name stands for, if any.

    A name stands for a coordinate when it is that letter, in any case, or ends with
    an underscore followed by that letter, e.g. 'x', 'Y', 'cell_x' or 'POSITION_Z'.

    Parameters
    ----------
    name : str
        The property name to check.

    Returns
    -------
    str | None
        'x', 'y' or 'z', or None if the name doesn't stand for a coordinate.
    """
    lowered = name.lower()
    for coordinate in _COORDINATES:
        if lowered == coordinate or lowered.endswith(f"_{coordinate}"):
            return coordinate
    return None


def _identify_space_props(
    cell_x_key: str | None,
    cell_y_key: str | None,
    cell_z_key: str | None,
    geff_md: geff.GeffMetadata | None,
    geff_graph: nx.DiGraph,
) -> tuple[str | None, str | None, str | None]:
    """
    Identify the space properties (x, y, z) from arguments or GEFF metadata.

    User-provided space properties must describe either a complete 2D coordinate
    system (`x` and `y`) or a complete 3D coordinate system (`x`, `y`, and `z`).
    Partial specifications and duplicate property names raise `ValueError`.

    The coordinates that are not provided are inferred, in this order:

    1. from the GEFF display hints (horizontal for x, vertical for y, depth for z);
    2. from the names of the space axes: an axis named 'x', 'y' or 'z' (any case),
       or ending with '_x', '_y' or '_z' (e.g. 'cell_x', 'POSITION_X');
    3. from the position of the remaining space axes whose names don't stand for
       a coordinate, with a warning: the last one for x, the one before for y,
       then z.

    The GEFF specification orders the axes as OME-Zarr does, i.e. as the
    dimensions of the image, where x comes last (e.g. t, z, y, x). Hence the
    names come before the positions, and positions are read from the end.
    Inferred properties are assigned at most once.
    Missing or unavailable properties remain `None`, so a 2D result is returned
    as `(x, y, None)`.

    Parameters
    ----------
    cell_x_key : str | None
        The key provided by the user to identify the x-coordinate.
    cell_y_key : str | None
        The key provided by the user to identify the y-coordinate.
    cell_z_key : str | None
        The key provided by the user to identify the z-coordinate.
    geff_md : geff.GeffMetadata | None
        The metadata from GEFF file.
    geff_graph : nx.DiGraph
        The geff graph.

    Returns
    -------
    tuple[str | None, str | None, str | None]
        The identified space properties.

    Raises
    ------
    ValueError
        If the provided space properties don't include both x and y, if duplicate
        property names are provided, or if the names of several space axes stand
        for the same coordinate.

    Warns
    -----
    UserWarning
        If a provided property is not on every node of the graph, in which case
        the coordinate is inferred instead, and if coordinates are inferred from
        the position of the space axes.

    Notes
    -----
    A property provided by the caller is replaced by metadata inference if it is
    not on every node of the graph.
    """
    space_keys = [cell_x_key, cell_y_key, cell_z_key]
    provided_keys = [key for key in space_keys if key is not None]
    if provided_keys and (cell_x_key is None or cell_y_key is None):
        raise ValueError("Space properties must include both x and y, and optionally z.")
    if len(set(provided_keys)) != len(provided_keys):
        raise ValueError("Space properties must be distinct.")

    for i, key in enumerate(space_keys):
        if key is not None and not _graph_has_node_prop(geff_graph, key):
            coordinate = _COORDINATES[i]
            logger.warning(
                f"The property '{key}' given as cell_{coordinate}_prop is not on every "
                f"node of the GEFF graph, so cell_{coordinate} will be inferred from "
                "the GEFF metadata instead, if possible.",
                stacklevel=3,
            )
            space_keys[i] = None

    # Fallback to GEFF display hints.
    hints = geff_md.display_hints if geff_md is not None else None
    hint_fields = ["display_horizontal", "display_vertical", "display_depth"]
    assigned_keys = {key for key in space_keys if key is not None}
    for i, (hint_field, key) in enumerate(zip(hint_fields, space_keys)):
        if key is None and hints is not None:
            space_key = getattr(hints, hint_field, None)
            if space_key is not None and space_key not in assigned_keys:
                if _graph_has_node_prop(geff_graph, space_key):
                    logger.info(
                        f"Valid space property inferred from display hints: '{space_key}'.",
                        stacklevel=3,
                    )
                    assigned_keys.add(space_key)
                else:
                    space_key = None
            else:
                space_key = None
            space_keys[i] = space_key

    # Fallback to the GEFF space axes, matched by name first.
    axes = geff_md.axes if geff_md is not None else None
    if axes is not None:
        space_axes = [
            axis.name
            for axis in axes
            if axis.type == "space"
            and axis.name is not None
            and axis.name not in assigned_keys
            and _graph_has_node_prop(geff_graph, axis.name)
        ]
        for i, coordinate in enumerate(_COORDINATES):
            if space_keys[i] is not None:
                continue
            matches = [
                name for name in space_axes if _coordinate_from_name(name) == coordinate
            ]
            if len(matches) > 1:
                matches_str = ", ".join(f"'{name}'" for name in matches)
                raise ValueError(
                    f"The names of several space axes of the GEFF file stand for the "
                    f"{coordinate} coordinate: {matches_str}. Choose the coordinate "
                    "properties with cell_x_prop, cell_y_prop and cell_z_prop."
                )
            if matches:
                space_keys[i] = matches[0]
                assigned_keys.add(matches[0])
                logger.info(
                    f"Valid space property inferred from axis name: '{matches[0]}'.",
                    stacklevel=3,
                )

        # Last resort: the position of the axes whose names say nothing, as in
        # OME-Zarr, where the spatial axes are ordered z, y, x: from the end.
        by_position = []
        for i, coordinate in enumerate(_COORDINATES):
            if space_keys[i] is not None:
                continue
            for name in reversed(space_axes):
                if name not in assigned_keys and _coordinate_from_name(name) is None:
                    space_keys[i] = name
                    assigned_keys.add(name)
                    by_position.append(f"'{name}' as cell_{coordinate}")
                    break
        if by_position:
            logger.warning(
                "Neither display hints nor axis names say which coordinate some space "
                "axes of the GEFF file are, so they were assigned by their position, "
                f"as in OME-Zarr where x comes last: {', '.join(by_position)}. If this "
                "is wrong, choose the coordinate properties with cell_x_prop, "
                "cell_y_prop and cell_z_prop.",
                stacklevel=3,
            )

    return space_keys[0], space_keys[1], space_keys[2]


def _resolve_prop_key(
    new_name: str,
    fallback: str,
    props_dict: dict,
    original_key: str,
    prop_type: PropertyType,
) -> str:
    """
    Resolve a unique property key in props_dict by trying new_name and fallback.

    Parameters
    ----------
    new_name : str
        The primary candidate for the new property key.
    fallback : str
        The fallback candidate for the new property key if new_name is already taken.
    props_dict : dict
        The dictionary of existing properties to check for key collisions.
    original_key : str
        The original property key that is being renamed, used for warning messages.
    prop_type : PropertyType
        The type of property being renamed (e.g., 'node' or 'edge'),
        used for warning messages.

    Returns
    -------
    str
        A unique property key to use for the new property.

    Warns
    -----
    UserWarning
        If new_name is not already taken in props_dict, a warning is issued
        indicating the rename.
        If new_name is already taken in props_dict, a warning is issued and fallback
        is returned as the new property key.

    Raises
    ------
    KeyError
        If both new_name and fallback are already taken in props_dict, a KeyError
        is raised indicating that the property cannot be registered in the metadata.
    """
    prop_type_str = property_type_to_strings(prop_type)
    if new_name not in props_dict:
        logger.warning(
            f"Property '{original_key}' ({prop_type_str}) has been renamed to '{new_name}'.",
            stacklevel=4,
        )
        return new_name
    if fallback not in props_dict:
        logger.warning(
            f"Property '{original_key}' ({prop_type_str}) has been renamed to '{fallback}' "
            f"('{new_name}' was already taken).",
            stacklevel=4,
        )
        return fallback
    raise KeyError(
        f"Cannot register property '{original_key}' ({prop_type_str}): both "
        f"'{new_name}' and '{fallback}' already exist in properties dictionary."
    )


def _extract_props_metadata(
    md: dict[str, geff_spec.PropMetadata],
    props_dict: dict[str, Property],
    prop_type: PropertyType,
    rename_map: dict[PropertyType, dict[str, str]],
) -> None:
    """
    Extract properties metadata from a given dictionary and update the props_dict.

    Parameters
    ----------
    md : dict[str, geff_spec.PropMetadata]
        The dictionary containing properties metadata.
    props_dict : dict[str, Property]
        The dictionary to update with extracted properties metadata.
    prop_type : PropertyType
        The type of property being extracted ('node' or 'edge').
    rename_map : dict[PropertyType, dict[str, str]]
        Mutable accumulator mapping property type to a dict of ``{old_key: new_key}``
        renames. When a key collision forces a rename, both the new and the existing
        property's mappings are recorded here so that the graph data can be updated
        accordingly.

    Raises
    ------
    ValueError
        If an unsupported property type is provided.
    KeyError
        If a property identifier already exists in props_dict for the same property
        type, or if both the primary and fallback rename candidates are already taken
        when resolving a node/edge key collision.
    """
    for key, prop in md.items():
        if key not in props_dict:
            props_dict[key] = Property(
                identifier=key,
                name=prop.name or key,
                description=prop.description or prop.name or key,
                provenance="geff",
                prop_type=prop_type,
                lin_type="CellLineage",
                dtype=prop.dtype,
                unit=prop.unit or None,
            )
        else:
            if props_dict[key].prop_type != prop_type:
                # The key must be unique but it already exists for nodes or edges,
                # so it needs to be renamed.
                if prop_type == PropertyType.NODE:
                    current_prefix, other_prefix = "cell", "link"
                elif prop_type == PropertyType.EDGE:
                    current_prefix, other_prefix = "link", "cell"
                else:
                    raise ValueError(
                        f"Unsupported property type: {property_type_to_strings(prop_type)}. "
                        "Expected PropertyType.NODE or PropertyType.EDGE."
                    )
                # Resolve a unique name for the new property.
                new_key = _resolve_prop_key(
                    f"{current_prefix}_{key}",
                    f"pycellin_{current_prefix}_{key}",
                    props_dict,
                    key,
                    prop_type,
                )
                props_dict[new_key] = Property(
                    identifier=new_key,
                    name=prop.name or key,
                    description=prop.description or prop.name or key,
                    provenance="geff",
                    prop_type=prop_type,
                    lin_type="CellLineage",
                    dtype=prop.dtype,
                    unit=prop.unit or None,
                )
                rename_map[prop_type][key] = new_key
                # Resolve a unique name for the existing colliding property.
                other_prop_type = props_dict[key].prop_type
                other_key = _resolve_prop_key(
                    f"{other_prefix}_{key}",
                    f"pycellin_{other_prefix}_{key}",
                    props_dict,
                    key,
                    other_prop_type,
                )
                other_prop = props_dict.pop(key)
                other_prop.identifier = other_key
                props_dict[other_key] = other_prop
                rename_map[other_prop_type][key] = other_key
            else:
                # GEFF ensures uniqueness of property keys for nodes and edges
                # separately, so this should never happen.
                raise KeyError(
                    f"Cannot register property '{key}': an identical identifier "
                    f"already exists in properties dictionary for "
                    f"{property_type_to_strings(prop_type)}s. "
                    "Please ensure unique property identifiers."
                )


def _extract_lin_props_metadata(
    md: dict[str, Any],
    props_dict: dict[str, Property],
    rename_map: dict[PropertyType, dict[str, str]],
) -> None:
    """
    Extract lineage properties metadata from a given dictionary and update the props_dict.

    Parameters
    ----------
    md : dict[str, Any]
        The dictionary containing lineage properties metadata.
    props_dict : dict[str, Property]
        The dictionary to update with extracted lineage properties metadata.
    rename_map : dict[PropertyType, dict[str, str]]
        Mutable accumulator mapping property type to a dict of ``{old_key: new_key}``
        renames. When a key collision forces a rename, both the new lineage property's
        mapping and the existing property's mapping are recorded here so that the graph
        data can be updated accordingly.

    Raises
    ------
    KeyError
        If a property identifier already exists in props_dict for lineages.
    """
    for key, prop in md.items():
        if key not in props_dict:
            props_dict[key] = Property(
                identifier=key,
                name=prop.get("name") or key,
                description=prop.get("description") or prop.get("name") or key,
                provenance="geff",
                prop_type=PropertyType.LINEAGE,
                lin_type="CellLineage",
                dtype=prop.get("dtype"),
                unit=prop.get("unit") or None,
            )
        else:
            if props_dict[key].prop_type != PropertyType.LINEAGE:
                # Resolve a unique name for the new lineage property.
                new_key = _resolve_prop_key(
                    f"lin_{key}",
                    f"pycellin_lin_{key}",
                    props_dict,
                    key,
                    PropertyType.LINEAGE,
                )
                props_dict[new_key] = Property(
                    identifier=new_key,
                    name=prop.get("name") or key,
                    description=prop.get("description") or prop.get("name") or key,
                    provenance="geff",
                    prop_type=PropertyType.LINEAGE,
                    lin_type="CellLineage",
                    dtype=prop.get("dtype"),
                    unit=prop.get("unit") or None,
                )
                rename_map[PropertyType.LINEAGE][key] = new_key
                # Resolve a unique name for the existing colliding property.
                existing_prop_type = props_dict[key].prop_type
                other_prefix = (
                    "cell" if PropertyType.NODE in existing_prop_type else "link"
                )
                other_key = _resolve_prop_key(
                    f"{other_prefix}_{key}",
                    f"pycellin_{other_prefix}_{key}",
                    props_dict,
                    key,
                    existing_prop_type,
                )
                other_prop = props_dict.pop(key)
                other_prop.identifier = other_key
                props_dict[other_key] = other_prop
                rename_map[existing_prop_type][key] = other_key
            else:
                raise KeyError(
                    f"Cannot register property '{key}' (lineage): an identical "
                    f"identifier already exists in properties dictionary. "
                    "Please ensure unique property identifiers."
                )


def _build_props_metadata(
    geff_md: geff.GeffMetadata,
    rename_map: dict[PropertyType, dict[str, str]],
) -> dict[str, Property]:
    """
    Read and extract properties metadata from geff metadata.

    Parameters
    ----------
    geff_md : geff.GeffMetadata
        The geff metadata object containing properties metadata.
    rename_map : dict[PropertyType, dict[str, str]]
        Mutable accumulator mapping property type to a dict of ``{old_key: new_key}``
        renames. Populated in-place whenever a key collision forces a rename during
        metadata extraction.

    Returns
    -------
    dict[str, Property]
        Dictionary mapping property identifiers to Property objects.
    """
    props_dict: dict[str, Property] = {}
    if geff_md.node_props_metadata:
        _extract_props_metadata(
            geff_md.node_props_metadata, props_dict, PropertyType.NODE, rename_map
        )
    if geff_md.edge_props_metadata:
        _extract_props_metadata(
            geff_md.edge_props_metadata, props_dict, PropertyType.EDGE, rename_map
        )

    # TODO: for now lineage properties are not associated to a specific tag but stored
    # somewhere in the "extra" field. We need to check recursively if there is a dict
    # key called "lineage_props_metadata" in the "extra" field.
    # For now I keep this, but it should be replaced by geffception at some point.
    if geff_md.extra:
        # Recursive search for the "lineage_props_metadata" key through the "extra"
        # field dict of dicts of dicts...
        lin_props_metadata = _recursive_dict_search(
            geff_md.extra, "lineage_props_metadata"
        )
        if lin_props_metadata is not None:
            _extract_lin_props_metadata(lin_props_metadata, props_dict, rename_map)

    return props_dict


def _get_prop_unit(
    prop: str,
    axis_type: Literal["time", "space"],
    node_props_md: dict[str, geff_spec.PropMetadata] | None,
    axes: list[geff_spec.Axis],
) -> str | None:
    """
    Retrieve the unit for a property from node properties metadata or axes.

    Node properties metadata is checked first. If the unit is missing, the
    function falls back to filtering the axes list by name and type.

    Parameters
    ----------
    prop : str
        The property name to look up.
    axis_type : Literal["time", "space"]
        The axis type to match when searching the axes list.
    node_props_md : dict[str, geff_spec.PropMetadata] | None
        Node properties metadata, keyed by property name.
    axes : list[geff_spec.Axis]
        The list of axes from GEFF metadata.

    Returns
    -------
    str | None
        The unit string if found, otherwise None.

    Raises
    ------
    AssertionError
        If more than one axis matches the given property name and axis type.
    """
    unit = None
    if node_props_md is not None and prop in node_props_md:
        unit = node_props_md[prop].unit
    if unit is None:
        matched_axes = [ax for ax in axes if ax.name == prop and ax.type == axis_type]
        assert len(matched_axes) <= 1, (
            f"Multiple axes with name '{prop}' and type '{axis_type}' found in"
            "GEFF metadata."
        )
        if matched_axes:
            unit = matched_axes[0].unit
    return unit


def _extract_axes_metadata(
    geff_md: geff.GeffMetadata,
    time_key: str,
    cell_x_key: str | None,
    cell_y_key: str | None,
    cell_z_key: str | None,
) -> dict[str, Any]:
    """
    Extract space and time units from GEFF metadata.

    Units are extracted from node properties metadata if available,
    and from axes metadata if not.

    Parameters
    ----------
    geff_md : geff.GeffMetadata
        The geff metadata object containing axes information.
    time_key : str
        The time property for the model.
    cell_x_key : str | None
        The x-coordinate property for the model, if any.
    cell_y_key : str | None
        The y-coordinate property for the model, if any.
    cell_z_key : str | None
        The z-coordinate property for the model, if any.

    Returns
    -------
    dict[str, Any]
        Dictionary containing space_unit and time_unit keys.

    Warns
    -----
    UserWarning
        If multiple space units are found in the axes, a warning is issued and no
        space unit is set at the model level.
    UserWarning
        If no unit is found for the time property, a warning is issued and no time
        unit is set at the model level.
    UserWarning
        If no unit is found for any space property, a warning is issued and no space
        unit is set at the model level.
    """
    units_metadata: dict[str, Any] = {}
    node_props_md = geff_md.node_props_metadata
    axes = geff_md.axes or []

    # Time unit.
    time_unit = _get_prop_unit(time_key, "time", node_props_md, axes)
    if time_unit is None:
        logger.warning(
            f"No unit found for time property '{time_key}' in node properties "
            "or axes. Not setting any time unit at the model level.",
            stacklevel=3,
        )
    else:
        units_metadata["time_unit"] = time_unit

    # Space units.
    if cell_x_key is None and cell_y_key is None and cell_z_key is None:
        logger.warning(
            "No coordinate properties found. "
            "Not setting any space unit at the model level.",
            stacklevel=3,
        )
        return units_metadata

    x_unit = (
        _get_prop_unit(cell_x_key, "space", node_props_md, axes) if cell_x_key else None
    )
    y_unit = (
        _get_prop_unit(cell_y_key, "space", node_props_md, axes) if cell_y_key else None
    )
    z_unit = (
        _get_prop_unit(cell_z_key, "space", node_props_md, axes) if cell_z_key else None
    )

    # Check unicity of space unit.
    space_units = {u for u in [x_unit, y_unit, z_unit] if u is not None}
    if len(space_units) > 1:
        logger.warning(
            f"Multiple space units found in node properties or axes: {space_units}. "
            "Not setting any space unit at the model level.",
            stacklevel=3,
        )
    elif len(space_units) == 1:
        units_metadata["space_unit"] = space_units.pop()
    else:
        logger.warning(
            "No unit found for space properties in node properties or axes. "
            "Not setting any space unit at the model level.",
            stacklevel=3,
        )

    return units_metadata


def _extract_generic_metadata(
    geff_file: Path | str, geff_md: geff.GeffMetadata
) -> dict[str, Any]:
    """
    Extract generic metadata for the model based on the GEFF file and its metadata.

    Parameters
    ----------
    geff_file : Path | str
        Path to the GEFF file.
    geff_md : geff.GeffMetadata
        The geff metadata object.

    Returns
    -------
    dict[str, Any]
        Dictionary containing generic metadata.

    Raises
    ------
    importlib.metadata.PackageNotFoundError
        If the pycellin package is not found when trying to get its version.
    """
    metadata: dict[str, Any] = {}
    metadata["name"] = Path(geff_file).stem
    metadata["file_location"] = geff_file
    metadata["provenance"] = "geff"
    metadata["date"] = str(datetime.now())
    try:
        version = importlib.metadata.version("pycellin")
    except importlib.metadata.PackageNotFoundError:
        version = "unknown"
    metadata["pycellin_version"] = version
    metadata["geff_version"] = geff_md.geff_version
    if geff_md.extra is not None:
        metadata["geff_extra"] = geff_md.extra

    return metadata


def _build_generic_metadata(
    geff_file: Path | str,
    geff_md: geff.GeffMetadata,
    time_key: str,
    cell_x_key: str | None,
    cell_y_key: str | None,
    cell_z_key: str | None,
) -> dict[str, Any]:
    """
    Build and return a dictionary containing pycellin generic metadata.

    Parameters
    ----------
    geff_file : Path | str
        Path to the geff file.
    geff_md : geff.GeffMetadata
        The geff metadata object to read from.
    time_key : str
        The time property for the model.
    cell_x_key : str | None
        The x-coordinate property for the model, if any.
    cell_y_key : str | None
        The y-coordinate property for the model, if any.
    cell_z_key : str | None
        The z-coordinate property for the model, if any.

    Returns
    -------
    dict[str, Any]
        Dictionary containing generic pycellin metadata.
    """
    metadata = _extract_generic_metadata(geff_file, geff_md)
    units_metadata = _extract_axes_metadata(
        geff_md, time_key, cell_x_key, cell_y_key, cell_z_key
    )
    metadata.update(units_metadata)
    metadata["reference_time_property"] = time_key

    return metadata


def _rename_reserved_prop(
    geff_graph: nx.DiGraph, props_md: dict[str, Property], key: str
) -> None:
    """
    Rename a GEFF node property that has the name of a property created by pycellin.

    pycellin creates its own 'cell_id' and 'lineage_id' properties. When the GEFF
    graph has a node property with the same name that is not used as identifier,
    its values and its declaration are kept under 'geff_<key>', and a warning is
    logged. Nothing happens if no node has the property.

    Parameters
    ----------
    geff_graph : nx.DiGraph
        The GEFF graph, updated in place.
    props_md : dict[str, Property]
        The properties metadata read from the GEFF file, updated in place.
    key : str
        Name of the property created by pycellin, 'cell_id' or 'lineage_id'.

    Raises
    ------
    ValueError
        If the GEFF file already has a 'geff_<key>' property.
    """
    if not any(key in data for _, data in geff_graph.nodes(data=True)):
        return
    new_key = f"geff_{key}"
    if new_key in props_md or any(
        new_key in data for _, data in geff_graph.nodes(data=True)
    ):
        raise ValueError(
            f"Cannot rename property '{key}' of the GEFF file to '{new_key}', "
            f"since '{new_key}' already exists. pycellin creates its own '{key}' "
            "property: rename one of these properties before loading the file."
        )

    for node in geff_graph.nodes:
        if key in geff_graph.nodes[node]:
            geff_graph.nodes[node][new_key] = geff_graph.nodes[node].pop(key)
    if key in props_md:
        prop = props_md.pop(key)
        prop.identifier = new_key
        props_md[new_key] = prop
    logger.warning(
        f"Property '{key}' of the GEFF file has been renamed to '{new_key}', since "
        f"pycellin creates its own '{key}' property."
    )


def _fallback_to_node_keys(
    geff_graph: nx.DiGraph, reason: str, props_md: dict[str, Property]
) -> None:
    """
    Fallback to using graph node keys as cell IDs, with a warning.

    A 'cell_id' property already in the graph is first renamed to 'geff_cell_id'.

    Parameters
    ----------
    geff_graph : nx.DiGraph
        The GEFF graph to update with fallback cell IDs.
    reason : str
        The reason for falling back to node keys, included in the warning message.
    props_md : dict[str, Property]
        The properties metadata read from the GEFF file, updated in place if the
        graph has a 'cell_id' property.

    Warns
    -----
    UserWarning
        Indicates that the fallback to node keys is occurring and the reason for it.
    """
    logger.warning(reason, stacklevel=3)
    _rename_reserved_prop(geff_graph, props_md, "cell_id")
    for node in geff_graph.nodes:
        geff_graph.nodes[node]["cell_id"] = node


def _get_cell_id_problem(geff_graph: nx.DiGraph, cell_id_key: str) -> str | None:
    """
    Explain why the values of a node property cannot identify cells.

    Cell IDs must be unique non-negative integers.

    Parameters
    ----------
    geff_graph : nx.DiGraph
        The GEFF graph. All its nodes must have the property.
    cell_id_key : str
        Name of the node property to check.

    Returns
    -------
    str | None
        The problem with the values of the property, or None if they can identify
        cells.
    """
    cell_ids = [geff_graph.nodes[node][cell_id_key] for node in geff_graph.nodes]
    if not all(
        isinstance(cell_id, int) and not isinstance(cell_id, bool) and cell_id >= 0
        for cell_id in cell_ids
    ):
        return f"Values in property '{cell_id_key}' are not all positive integers."
    if len(set(cell_ids)) != len(cell_ids):
        return (
            f"Duplicate values found in property '{cell_id_key}' across graph nodes."
        )
    return None


def _ensure_valid_cell_id(
    geff_graph: nx.DiGraph, cell_id_key: str | None, props_md: dict[str, Property]
) -> str:
    """
    Ensure that a valid cell ID property exists and is consistent with graph node IDs.

    If ``cell_id_key`` is None, the function uses the 'cell_id' property of the
    graph if it can identify cells, else it creates a 'cell_id' property from the
    NetworkX node keys. If ``cell_id_key`` is provided, it verifies uniqueness of
    the property, that it exists on all nodes and is a positive integer. If not,
    it falls back to creating a 'cell_id' property from node keys. If the property
    is valid but its values differ from node keys, the graph node keys are
    updated to match the provided IDs to avoid later inconsistencies.

    When the cell identifier is not the 'cell_id' property of the graph, that
    property is renamed to 'geff_cell_id', so that pycellin can create its own.

    Parameters
    ----------
    geff_graph : nx.DiGraph
        The GEFF graph to validate or update.
    cell_id_key : str | None
        Name of the node property that identifies cells, or None to use the
        'cell_id' property or the graph node keys.
    props_md : dict[str, Property]
        The properties metadata read from the GEFF file, updated in place if the
        graph has a 'cell_id' property that is renamed.

    Returns
    -------
    str
        The name of the property used as cell identifier after validation or fallback.

    Warns
    -----
    UserWarning
        If ``cell_id_key`` is provided but missing on some nodes, triggering a
        fallback to generated ``cell_id`` values from node keys.
        If ``cell_id_key`` is provided but contains duplicate values across
        nodes, triggering a fallback to generated ``cell_id`` values from node keys.
    """
    inferred = cell_id_key is None
    if inferred:
        cell_id_key = "cell_id"
    if not _graph_has_node_prop(geff_graph, cell_id_key):
        if inferred:
            reason = "No cell identifier property provided."
        else:
            reason = (
                f"The provided property '{cell_id_key}' is not present on all nodes "
                "of the GEFF graph."
            )
    else:
        problem = _get_cell_id_problem(geff_graph, cell_id_key)
        if problem is None:
            reason = None
        else:
            reason = f"{problem} This property cannot be used as cell identifier."

    if reason is not None:
        _fallback_to_node_keys(
            geff_graph,
            f"{reason} A 'cell_id' property will be created from node keys instead.",
            props_md,
        )
        return "cell_id"

    if inferred:
        logger.info(
            "Cell identifier inferred from existing graph property: 'cell_id'.",
            stacklevel=2,
        )
    elif cell_id_key != "cell_id":
        _rename_reserved_prop(geff_graph, props_md, "cell_id")
    mapping = {node: geff_graph.nodes[node][cell_id_key] for node in geff_graph.nodes}
    nx.relabel_nodes(geff_graph, mapping, copy=False)
    return cell_id_key


def _get_coordinate_renames(
    cell_x_key: str | None,
    cell_y_key: str | None,
    cell_z_key: str | None,
    rename_map: dict[PropertyType, dict[str, str]],
) -> dict[str, str]:
    """
    Map the current name of each coordinate property to its pycellin name.

    The current name of a coordinate is its name after the collision renames
    recorded in *rename_map*. Coordinates already named like in pycellin are left
    out.

    Parameters
    ----------
    cell_x_key : str | None
        The x-coordinate key name in the GEFF file, if any.
    cell_y_key : str | None
        The y-coordinate key name in the GEFF file, if any.
    cell_z_key : str | None
        The z-coordinate key name in the GEFF file, if any.
    rename_map : dict[PropertyType, dict[str, str]]
        The ``{old_key: new_key}`` collision renames per property type, collected
        during metadata extraction.

    Returns
    -------
    dict[str, str]
        ``{current_key: pycellin_key}`` for each coordinate to rename, in x, y, z
        order.
    """
    renames = {}
    for coordinate, key in zip(_COORDINATES, (cell_x_key, cell_y_key, cell_z_key)):
        if key is None:
            continue
        current_key = rename_map[PropertyType.NODE].get(key, key)
        pycellin_key = f"cell_{coordinate}"
        if current_key != pycellin_key:
            renames[current_key] = pycellin_key
    return renames


def _standardize_properties_data(
    lineages: list[CellLineage],
    lin_id_key: str,
    cell_id_key: str,
    cell_x_key: str | None,
    cell_y_key: str | None,
    cell_z_key: str | None,
    rename_map: dict[PropertyType, dict[str, str]],
) -> None:
    """
    Standardize properties data in lineages to match pycellin conventions.

    This function updates the property keys in lineage node data to use
    standardized pycellin naming conventions (e.g., 'cell_id', 'cell_x').
    It also applies any key renames recorded in *rename_map* during metadata
    extraction so that the graph data stays consistent with the metadata.

    Parameters
    ----------
    lineages : list[CellLineage]
        List of CellLineage objects to standardize.
    lin_id_key : str
        The current lineage ID key name. If not "lineage_id", this property will be
        renamed in two places: (1) as a node attribute on all nodes within each
        lineage, and (2) as a graph attribute for each lineage object.
    cell_id_key : str
        The current cell ID key name.
    cell_x_key : str | None
        The current x-coordinate key name, if any.
    cell_y_key : str | None
        The current y-coordinate key name, if any.
    cell_z_key : str | None
        The current z-coordinate key name, if any.
    rename_map : dict[PropertyType, dict[str, str]]
        Accumulator of ``{old_key: new_key}`` renames per property type
        (NODE, EDGE, LINEAGE) collected during metadata extraction.
        Applied to each lineage's node attributes, edge attributes, and
        graph-level attributes respectively.
    """
    coordinate_renames = _get_coordinate_renames(
        cell_x_key, cell_y_key, cell_z_key, rename_map
    )
    for lin in lineages:
        # Collision renames as recorded during metadata extraction.
        for old_key, new_key in rename_map[PropertyType.NODE].items():
            _update_node_prop_key(lin, old_key=old_key, new_key=new_key)
        for old_key, new_key in rename_map[PropertyType.EDGE].items():
            _update_edge_prop_key(lin, old_key=old_key, new_key=new_key)
        for old_key, new_key in rename_map[PropertyType.LINEAGE].items():
            _update_lineage_prop_key(lin, old_key=old_key, new_key=new_key)

        # Standard pycellin property renames.
        if lin_id_key != "lineage_id":
            _update_node_prop_key(lin, old_key=lin_id_key, new_key="lineage_id")
        if cell_id_key != "cell_id":
            _update_node_prop_key(lin, old_key=cell_id_key, new_key="cell_id")
        # The coordinates are renamed all at once: the current name of one can be
        # the pycellin name of another (e.g. 'cell_y' used as x), so renaming them
        # one after the other would overwrite values.
        for node in lin.nodes:
            attrs = lin.nodes[node]
            values = {
                new_key: attrs.pop(old_key)
                for old_key, new_key in coordinate_renames.items()
                if old_key in attrs
            }
            attrs.update(values)

    if lin_id_key != "lineage_id":
        _update_lineages_ids_key(lineages, lin_id_key)


def _standardize_props_metadata(
    props_md: dict[str, Property],
    lin_id_key: str | None,
    cell_id_key: str | None,
    cell_x_key: str | None,
    cell_y_key: str | None,
    cell_z_key: str | None,
    space_unit: str | None,
    rename_map: dict[PropertyType, dict[str, str]],
) -> None:
    """
    Normalize properties metadata to match pycellin conventions.

    This function ensures that standard pycellin properties exist in the metadata
    and renames them if needed to follow pycellin conventions.

    Parameters
    ----------
    props_md : dict[str, Property]
        The properties metadata dictionary to normalize.cell_id_prop,
    lin_id_key : str | None
        The current lineage ID property name, if any.
    cell_id_key : str | None
        The current cell ID property name, if any.
    cell_x_key : str | None
        The current x-coordinate property name, if any.
    cell_y_key : str | None
        The current y-coordinate property name, if any.
    cell_z_key : str | None
        The current z-coordinate property name, if any.
    space_unit : str | None
        The space unit to use for coordinate properties.
    rename_map : dict[PropertyType, dict[str, str]]
        Accumulator of ``{old_key: new_key}`` renames per property type collected
        during metadata extraction. Applied here to ensure that any standard
        properties that needed to be renamed during metadata extraction are also
        renamed in the metadata dictionary.
    """
    # Ensure standard pycellin properties exist and are properly named.
    if lin_id_key in props_md:
        if lin_id_key != "lineage_id":
            props_md["lineage_id"] = props_md.pop(lin_id_key)
        props_md["lineage_id"].identifier = "lineage_id"
        props_md["lineage_id"].prop_type = PropertyType.NODE | PropertyType.LINEAGE
    else:
        props_md["lineage_id"] = create_lineage_id_property(provenance="geff")

    if cell_id_key in props_md:
        if cell_id_key != "cell_id":
            props_md["cell_id"] = props_md.pop(cell_id_key)
        props_md["cell_id"].identifier = "cell_id"
    else:
        props_md["cell_id"] = create_cell_id_property(provenance="geff")

    # Create or standardize coordinate property keys.
    coordinate_keys = list(zip(_COORDINATES, (cell_x_key, cell_y_key, cell_z_key)))
    for _, geff_key in coordinate_keys:
        if geff_key is not None:
            # Remove the original key if it was renamed to a different key.
            current_key = rename_map[PropertyType.NODE].get(geff_key, geff_key)
            if geff_key in props_md and geff_key != current_key:
                props_md.pop(geff_key)
    # All at once, as in _standardize_properties_data(): the current name of a
    # coordinate can be the pycellin name of another.
    renames = _get_coordinate_renames(cell_x_key, cell_y_key, cell_z_key, rename_map)
    moved = {
        new_key: props_md.pop(old_key)
        for old_key, new_key in renames.items()
        if old_key in props_md
    }
    props_md.update(moved)
    for axis, geff_key in coordinate_keys:
        if geff_key is None:
            continue
        pycellin_key = f"cell_{axis}"
        if pycellin_key in props_md:
            props_md[pycellin_key].identifier = pycellin_key
        else:
            props_md[pycellin_key] = create_cell_coord_property(
                unit=space_unit, axis=axis, provenance="geff"
            )


def load_GEFF(
    geff_file: Path | str,
    lineage_id_prop: str | None = None,
    cell_id_prop: str | None = None,
    cell_x_prop: str | None = None,
    cell_y_prop: str | None = None,
    cell_z_prop: str | None = None,
    time_prop: str | None = None,
    structure_validation: bool = True,
) -> Model:
    """
    Load a GEFF file and return a pycellin model containing the data and metadata.

    Parameters
    ----------
    geff_file : Path | str
        Path to the GEFF file to load.
    lineage_id_prop: str | None, optional
        Name of the property that identifies lineages in the GEFF file.
        If None, the function will try to infer it from the GEFF metadata, then
        use the 'lineage_id' property of the file if its values match the
        disconnected parts of the graph, else autogenerate lineage IDs based on
        weakly connected components.
    cell_id_prop : str | None, optional
        Name of the property that identifies cells in the GEFF file.
        If None, the 'cell_id' property of the file is used if its values are
        unique non-negative integers, else a 'cell_id' property will be created
        and populated based on GEFF IDs array (graph node IDs).
    cell_x_prop : str | None, optional
        Name of the node property that contains the x-coordinate. Provide this
        together with ``cell_y_prop`` for 2D data, or with both ``cell_y_prop``
        and ``cell_z_prop`` for 3D data. If all coordinate properties are
        ``None``, they will be inferred from GEFF metadata.
    cell_y_prop : str | None, optional
        Name of the node property that contains the y-coordinate. It must be
        provided together with ``cell_x_prop`` when coordinates are specified
        explicitly. If all coordinate properties are ``None``, it will be
        inferred from GEFF metadata.
    cell_z_prop : str | None, optional
        Name of the node property that contains the z-coordinate for 3D data.
        Omit it for 2D data. If all coordinate properties are ``None``, it will
        be inferred from GEFF metadata when available.
    time_prop : str | None, optional
        Name of the property to use as the reference time property.
        If None, it will be inferred from the GEFF metadata. If the property is not
        on every node of the graph, a warning is logged and it is inferred too.
    structure_validation : bool, optional
        Whether to validate the GEFF file's structure, i.e. to check that it is
        compliant with the GEFF specification. Default is True.

    Notes
    -----
    When coordinate properties are not provided, ``load_GEFF`` infers them from
    the GEFF metadata: first from the display hints, then from the names of the
    space axes ('x', 'y' and 'z' in any case, or names ending with '_x', '_y'
    and '_z', such as 'cell_x' or 'POSITION_X'), and last from the position of
    the remaining space axes, as in OME-Zarr where x comes last, with a warning.
    Inferred properties are assigned at most once, and a 2D dataset is
    represented by ``(x, y, None)`` internally. Coordinate properties in the
    resulting model are normalized to ``cell_x``, ``cell_y``, and ``cell_z`` when
    available.

    If a supplied coordinate property is not on every node of the graph, a
    warning is logged and inference is attempted for that coordinate from GEFF
    metadata. Explicit coordinate
    arguments must otherwise describe either a complete 2D set (x and y) or a
    complete 3D set (x, y, and z); partial specifications and duplicate
    property names are invalid.

    pycellin creates its own 'cell_id' and 'lineage_id' properties. A 'cell_id'
    or 'lineage_id' property of the GEFF file that is not used as identifier is
    kept under the name 'geff_cell_id' or 'geff_lineage_id', with a warning.

    Returns
    -------
    Model
        A pycellin model containing the data and metadata from the GEFF file.

    Raises
    ------
    ValueError
        If the GEFF graph is undirected, as pycellin does not support undirected
        graphs, if the coordinate arguments don't include both x and y or contain
        duplicate property names, if the names of several space axes stand for
        the same coordinate, or if a 'cell_id' or 'lineage_id' property of the
        GEFF file must be renamed but the file already has a 'geff_cell_id' or
        'geff_lineage_id' property.
    """
    # Read the GEFF file.
    geff_graph, geff_md = geff.read(geff_file, structure_validation=structure_validation)
    if not geff_md.directed:
        raise ValueError(
            "The GEFF graph is undirected: pycellin does not support undirected graphs."
        )

    # Identify specific properties.
    lineage_id_prop = _identify_lin_id_prop(
        lineage_id_prop, geff_md.track_node_props, geff_graph
    )
    time_prop = _identify_time_prop(time_prop, geff_md, geff_graph)
    cell_x_prop, cell_y_prop, cell_z_prop = _identify_space_props(
        cell_x_prop, cell_y_prop, cell_z_prop, geff_md, geff_graph
    )

    # Extract and dispatch metadata.
    generic_md = _build_generic_metadata(
        geff_file, geff_md, time_prop, cell_x_prop, cell_y_prop, cell_z_prop
    )
    rename_map: dict[PropertyType, dict[str, str]] = {
        PropertyType.NODE: {},
        PropertyType.EDGE: {},
        PropertyType.LINEAGE: {},
    }
    props_md = _build_props_metadata(geff_md, rename_map)

    # Split the graph into lineages. pycellin creates its own 'cell_id' and
    # 'lineage_id' properties, so GEFF properties with these names that are not
    # used as identifiers are renamed first.
    cell_id_prop = _ensure_valid_cell_id(geff_graph, cell_id_prop, props_md)
    if lineage_id_prop != "lineage_id":
        _rename_reserved_prop(geff_graph, props_md, "lineage_id")
    lineages = _split_graph_into_lineages(geff_graph, lineage_id_key=lineage_id_prop)
    if lineage_id_prop is None:
        lineage_id_prop = "lineage_id"

    # Rename properties to match pycellin conventions.
    _standardize_properties_data(
        lineages=lineages,
        lin_id_key=lineage_id_prop,
        cell_id_key=cell_id_prop,
        cell_x_key=cell_x_prop,
        cell_y_key=cell_y_prop,
        cell_z_key=cell_z_prop,
        rename_map=rename_map,
    )
    _standardize_props_metadata(
        props_md=props_md,
        lin_id_key=lineage_id_prop,
        cell_id_key=cell_id_prop,
        cell_x_key=cell_x_prop,
        cell_y_key=cell_y_prop,
        cell_z_key=cell_z_prop,
        space_unit=generic_md.get("space_unit"),
        rename_map=rename_map,
    )

    # Create the model.
    model = Model(
        model_metadata=generic_md,
        props_metadata=PropsMetadata(props=props_md),
        data=Data({lin.graph["lineage_id"]: lin for lin in lineages}),
    )
    check_fusions(model)  # pycellin DOES NOT support fusion events

    return model


